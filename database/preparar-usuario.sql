\set ON_ERROR_STOP on
\getenv clave_app APP_DB_PASSWORD

SELECT format(
  'CREATE ROLE inventario_app LOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION NOBYPASSRLS PASSWORD %L',
  :'clave_app'
)
WHERE NOT EXISTS (
  SELECT 1 FROM pg_roles WHERE rolname = 'inventario_app'
)
\gexec

ALTER ROLE inventario_app
  NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION NOBYPASSRLS;

REVOKE ALL ON DATABASE inventario FROM PUBLIC;
GRANT CONNECT ON DATABASE inventario TO inventario_app;

REVOKE ALL ON SCHEMA public FROM PUBLIC;
GRANT USAGE ON SCHEMA public TO inventario_app;
